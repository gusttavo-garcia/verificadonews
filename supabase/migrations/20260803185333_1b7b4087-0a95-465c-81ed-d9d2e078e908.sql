A arroba do boi gordo **não está** em R$ 400. Trata-se de uma **projeção** de parte das consultorias do setor para o fim de 2026 — e há divergência entre analistas sobre o teto da alta. Publicações que anunciam o valor como fato consumado induzem o leitor ao erro.

## O que dizem os dados oficiais

O Indicador do Boi Gordo CEPEA/ESALQ (à vista, arroba de 15 kg, sem Funrural) registrou **R$ 342,65 em 22/07/2026**, com variação de 1,86% no mês. Ao longo de julho, o indicador oscilou entre cerca de R$ 324 e R$ 343 — bem distante dos R$ 400.

## De onde vem a projeção de R$ 400

- **Scot Consultoria**: o analista Felipe Fabbri projeta que a arroba pode chegar a R$ 400 em algum momento no fim de 2026, citando menor oferta de boiadas, demanda interna aquecida em ano eleitoral e efeito Copa do Mundo. O próprio analista ressalva que "mais importante que o preço é a preservação da margem".
- **Mercado futuro (B3)**: os contratos com vencimento em dezembro de 2026 vêm se descolando dos demais, precificando o pico do ano no último mês. Contratos para o início de 2027 já aparecem acima de R$ 370 por arroba.
- **Outras consultorias** avaliam recuperação no segundo semestre, mas divergem sobre até onde a valorização vai — nem todas trabalham com R$ 400.

## O que sustenta a expectativa de alta

- Redução na oferta de animais prontos para abate no ciclo pecuário.
- Exportações aquecidas, com demanda firme no mercado externo.
- Demanda interna reforçada no segundo semestre.

## O que pode frear a alta

- Pressão baixista registrada no mercado físico no fim de julho de 2026.
- Custo de produção e reposição do bezerro, que corroem a margem mesmo com arroba alta.
- Câmbio e eventuais barreiras comerciais, que afetam diretamente o ritmo das exportações.

## Conclusão

É **parcialmente verdade** que a arroba pode bater R$ 400: existe projeção séria nesse sentido para o fim de 2026, amparada por fundamentos de oferta e demanda. Mas é **falso** afirmar que esse é o preço atual ou que a marca está garantida. Quem for tomar decisão de compra, venda ou financiamento deve acompanhar o indicador diário do CEPEA e os ajustes da B3, não manchetes.

